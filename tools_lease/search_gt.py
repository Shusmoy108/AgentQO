#!/usr/bin/env python3
"""Write P6/search_ground_truth.md from the Mac mirror (no model calls, no search algorithm).
True front: plans not dominated on (accuracy max, API cost min); accuracy from h3_plans.csv, API cost (api_usd) from
P6/<setting>/cost/plan_costs.csv (A16 math_tiers: P6/math_tiers/tiers/tier_pareto.csv). Hypervolume: 2D area dominated
by the front with cost normalized by the setting's most expensive plan, reference point (cost 1, accuracy 0)."""
import csv, os, sys
M = os.path.expanduser("~/AgentQO_results/v2")
SET = [("math_q15_7", "P1", "P2", "A"), ("hotpot_q15_7", "P1", "P2", "A"), ("hotpot_iso_q15_7", "P1", "P2", "A"),
       ("math_q3_14", "P3", "P3", "B"), ("math_granite", "P4", "P4", "B"), ("hotpot_granite", "P4", "P4", "B"),
       ("hotpot_iso_granite", "P4", "P4", "B"), ("math_phi", "P4b", "P4b", "B"), ("hotpot_phi", "P4b", "P4b", "B"),
       ("complex_q15_7", "P2c", "P2c", "A"), ("math_tiers", "P2b", "P2b", "A")]
def rd(p): return list(csv.DictReader(open(p)))
def front_hv(acc, cost):
    names = list(acc); cmax = max(cost.values()) or 1.0
    fr = sorted((n for n in names if not any(acc[m] >= acc[n] and cost[m] <= cost[n] and (acc[m] > acc[n] or cost[m] < cost[n]) for m in names)),
                key=lambda n: cost[n])
    hv = 0.0
    for i, n in enumerate(fr):
        nxt = cost[fr[i + 1]] / cmax if i + 1 < len(fr) else 1.0
        hv += (nxt - cost[n] / cmax) * acc[n]
    return fr, hv
out = ["# Search ground truth (P6)", "",
       "One row per setting with exhaustive plans. True front: plans not dominated on accuracy (higher is better) and API cost",
       "(api_usd, lower is better). Hypervolume: 2D area dominated by the true front, cost normalized by the setting's most",
       "expensive plan, reference point (cost 1, accuracy 0). Generated by tools/search_gt.py from the lease results; no search",
       "algorithm was implemented or run during the lease.", "",
       "| setting | plans | eval problems | on true front | front share | hypervolume | per-problem complete | usable for search |",
       "|---|---|---|---|---|---|---|---|"]
files = ["", "## Files a search evaluation needs (paths under results/v2/)", ""]
for s, lp, pp, vm in SET:
    base = f"{M}/vm-{vm}/results/v2"
    plans = rd(f"{base}/{pp}/{s}/plans/h3_plans.csv")
    acc = {r["plan"]: float(r["accuracy"]) for r in plans}
    if s == "math_tiers":
        cost = {r["plan"]: float(r["api_usd"]) for r in rd(f"{M}/vm-A/results/v2/P6/math_tiers/tiers/tier_pareto.csv")}
        cfile = "P6/math_tiers/tiers/tier_pareto.csv"
    else:
        cost = {r["plan"]: float(r["api_usd"]) for r in rd(f"{M}/vm-A/results/v2/P6/{s}/cost/plan_costs.csv")}
        cfile = f"P6/{s}/cost/plan_costs.csv"
    pp_rows = rd(f"{base}/{pp}/{s}/plans/h3_per_problem.csv")
    probs = {r["task_id"] for r in pp_rows}; pairs = {(r["plan"], r["task_id"]) for r in pp_rows}
    complete = len(pairs) == len(acc) * len(probs) and set(acc) == set(cost)
    fr, hv = front_hv(acc, cost)
    out.append(f"| {s} | {len(acc)} | {len(probs)} | {len(fr)} | {len(fr)/len(acc):.3f} | {hv:.4f} | "
               f"{'yes' if complete else 'NO'} ({len(pairs)} of {len(acc)*len(probs)}) | {'yes' if complete else 'not usable for search'} |")
    calls = f"{pp}/{s}/plans/h3_calls.csv" + (".gz" if os.path.exists(f"{base}/{pp}/{s}/plans/h3_calls.csv.gz") else "")
    files.append(f"- **{s}**: plans {pp}/{s}/plans/h3_plans.csv; per problem {pp}/{s}/plans/h3_per_problem.csv; per call {calls}; "
                 f"API cost {cfile}; labels {lp}/{s}/labels/labels_v2.csv and labels_v2_per_problem.csv; front: {', '.join(fr)}")
out += files + ["", "X1-X7 (exploratory) are added to this file as they finish."]
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("\n".join(out[:20]))
