from __future__ import annotations

import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy import stats  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from agentqo.search.ground_truth import SETTINGS, load_setting, true_front  # noqa: E402
from agentqo.search.methods import METHODS_2D  # noqa: E402
from agentqo.search.metrics import budget_for  # noqa: E402
from agentqo.search.surrogates import label_terms  # noqa: E402

OUT = Path(__file__).resolve().parents[2] / "results" / "search"
FIG = OUT / "figures"
TAU = 0.0134         # HV-ratio tie threshold from X4 (docs/search_log.md)
MAIN = "nsga2_pairwise_m3"
COMPARATORS = {"(a) nsga2_indep_add": "nsga2_indep_add", "(b) abacus": "abacus", "(c) random": "random",
               "(d) greedy_uv": "greedy_uv", "(e) rule_structural": "rule_structural",
               "(e) rule_output": "rule_output", "(e) rule_confident_uv": "rule_confident_uv"}
COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#6250d6"]  # dataviz palette, fixed order


def ci(x):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    if len(x) < 2 or np.std(x) == 0:
        return (np.mean(x) if len(x) else np.nan,) * 2
    h = stats.t.ppf(0.975, len(x) - 1) * np.std(x, ddof=1) / np.sqrt(len(x))
    return np.mean(x) - h, np.mean(x) + h


def summarize(d, keys, metrics):
    rows = []
    for k, g in d.groupby(keys):
        r = dict(zip(keys, k))
        for m in metrics:
            lo, hi = ci(g[m])
            r[f"{m}_mean"], r[f"{m}_ci_low"], r[f"{m}_ci_high"] = g[m].mean(), lo, hi
        rows.append(r)
    return pd.DataFrame(rows)


def paired(d, metric, a, b):
    """Per (setting, budget_frac) cell: W / T / L of method a vs b on metric (higher is better)."""
    out = []
    for (s, f), g in d.groupby(["setting", "budget_frac"]):
        x = g[g.method == a].set_index("seed")[metric]
        y = g[g.method == b].set_index("seed")[metric]
        diff = (x - y).dropna()
        lo, hi = ci(diff)
        m = diff.mean()
        res = "W" if m > TAU and lo > 0 else "L" if m < -TAU and hi < 0 else "T"
        out.append({"setting": s, "budget_frac": f, "a": a, "b": b, "diff": m, "ci_low": lo, "ci_high": hi, "res": res})
    return pd.DataFrame(out)


def wtl(p):
    c = p.res.value_counts()
    return int(c.get("W", 0)), int(c.get("T", 0)), int(c.get("L", 0))


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    d = pd.read_csv(OUT / "results.csv")
    d2, d3 = d[d.objectives == "acc_cost"], d[d.objectives == "acc_cost_p95"]
    m2 = ["hv_ratio", "igd", "regret_p25", "regret_p50", "regret_p75", "n_verified", "surrogate_rho", "wall_s"]
    s2 = summarize(d2, ["setting", "n_plans", "method", "budget_frac", "budget"], m2)
    s2.to_csv(OUT / "summary_acc_cost.csv", index=False)
    s3 = summarize(d3, ["setting", "n_plans", "latency_source", "method", "budget_frac", "budget"], ["hv3_ratio", "n_verified", "wall_s"])
    s3.to_csv(OUT / "summary_acc_cost_p95.csv", index=False)
    settings = list(dict.fromkeys(d2.setting))
    md = ["# Search hypotheses (S1-S5)", "",
          "Generated by scripts/search/summarize.py from results/search/results.csv (30 seeds, mean and 95% CI).",
          "Pre-registration: docs/search_prereg.md (tag search-prereg-20261117T2127Z); decision rules and tie",
          f"threshold (tau = {TAU} HV ratio, from X4) in docs/search_log.md.", ""]

    # ---- S1
    big = s2[(s2.n_plans >= 256) & (s2.method == MAIN)]
    rows = big[big.budget_frac == 0.10]
    s1 = all(rows.hv_ratio_mean >= 0.95)
    md += ["## S1: " + ("HELD" if s1 else "FAILED"), "",
           "NSGA-II + pairwise_corrected (m 3), settings with >= 256 plans: mean HV ratio [95% CI] per budget.", "",
           "| setting | plans | " + " | ".join(f"{int(f*100)}%" for f in sorted(big.budget_frac.unique())) + " |",
           "|---|---|" + "---|" * big.budget_frac.nunique()]
    for s, g in big.groupby("setting"):
        g = g.sort_values("budget_frac")
        md.append(f"| {s} | {g.n_plans.iloc[0]} | " + " | ".join(
            f"{r.hv_ratio_mean:.3f} [{r.hv_ratio_ci_low:.3f}, {r.hv_ratio_ci_high:.3f}] (B={r.budget})" for r in g.itertuples()) + " |")
    md += ["", "Note: the independence-additive surrogate and Abacus-style reach the 95% bar too (see S2), so S1 says the",
           "search works at <= 10% verification, not that the pair correction is what makes it work.", ""]

    # ---- S2
    pw = {k: paired(d2, "hv_ratio", MAIN, v) for k, v in COMPARATORS.items()}
    pd.concat(pw.values()).to_csv(OUT / "s2_paired_cells.csv", index=False)
    beats = {}
    md += ["## S2: {S2}", "", f"Paired per cell (11 settings x 5 budgets = 55 cells), {MAIN} minus comparator, HV ratio.",
           "W/T/L as in docs/search_log.md.", "",
           "| comparator | W | T | L | mean diff (all cells) | >=256-plan cells W/T/L | verdict |", "|---|---|---|---|---|---|---|"]
    for k, p in pw.items():
        w, t, l = wtl(p)
        wb, tb, lb = wtl(p[p.setting.isin(["complex_q15_7", "math_tiers"])])
        v = "beats" if (w > l and w >= 28) else "loses" if l > w else "tie"
        beats[k] = v
        md.append(f"| {k} | {w} | {t} | {l} | {p['diff'].mean():+.4f} | {wb}/{tb}/{lb} | {v} |")
    nb = sum(v == "beats" for v in beats.values())
    S2 = "HELD" if nb == len(beats) else "PARTIAL" if nb else "FAILED"
    md[md.index("## S2: {S2}")] = f"## S2: {S2}"
    md += ["", f"Beats {nb} of {len(beats)} comparators. Other surrogates and engines (exploratory, same budget, mean HV",
           "ratio over all cells): " + ", ".join(f"{m} {d2[d2.method == m].hv_ratio.mean():.3f}" for m in METHODS_2D), ""]

    # ---- S3
    rows3 = []
    for s in settings:
        st = load_setting(s, with_latency=False)
        z = np.zeros(st.n, dtype=int)
        b = st.acc[st.row(z)]
        single = np.zeros((st.n, len(st.tiers)))
        for i in range(st.n):
            for t in range(1, len(st.tiers)):
                g = z.copy(); g[i] = t
                single[i, t] = st.acc[st.row(g)] - b
        est = np.clip(b + single[np.arange(st.n), st.genomes].sum(1), 0, 1)
        gap = (d2[(d2.setting == s) & (d2.method == MAIN)].hv_ratio.mean()
               - d2[(d2.setting == s) & (d2.method == "nsga2_indep_add")].hv_ratio.mean())
        rows3.append({"setting": s, "indep_error_mae": np.abs(est - st.acc).mean(), "gap_pairwise_minus_indep": gap})
    t3 = pd.DataFrame(rows3).sort_values("indep_error_mae", ascending=False)
    t3.to_csv(OUT / "s3_interaction_vs_gap.csv", index=False)
    rho, p = stats.spearmanr(t3.indep_error_mae, t3.gap_pairwise_minus_indep)
    S3 = "HELD" if rho > 0 and p < 0.05 else "PARTIAL" if rho > 0 else "FAILED"
    md += [f"## S3: {S3}", "", f"Spearman rho = {rho:.3f} (p = {p:.3f}, 11 settings) between the independence error and the",
           "surrogate gap (pairwise m3 minus independence additive, mean HV ratio over budgets).", "",
           "| setting | independence MAE (eval singles) | gap |", "|---|---|---|"]
    md += [f"| {r.setting} | {r.indep_error_mae:.4f} | {r.gap_pairwise_minus_indep:+.4f} |" for r in t3.itertuples()]
    md.append("")

    # ---- S4
    p4 = []
    for (s, f), g in d3.groupby(["setting", "budget_frac"]):
        x = g[g.method == "joint_nsga2_pairwise_m3"].set_index("seed").hv3_ratio
        y = g[g.method == "plan_first_nsga2_pairwise_m3"].set_index("seed").hv3_ratio
        diff = x - y
        lo, hi = ci(diff)
        res = "W" if diff.mean() > TAU and lo > 0 else "L" if diff.mean() < -TAU and hi < 0 else "T"
        p4.append({"setting": s, "budget_frac": f, "latency_source": g.latency_source.iloc[0], "diff": diff.mean(),
                   "ci_low": lo, "ci_high": hi, "res": res})
    p4 = pd.DataFrame(p4)
    p4.to_csv(OUT / "s4_paired_cells.csv", index=False)
    w, t, l = wtl(p4)
    S4 = "HELD" if (w >= len(p4) / 2 and l == 0) else "FAILED" if (w == 0 or l > w) else "PARTIAL"
    md += [f"## S4: {S4}", "", f"Joint (plan + placement gene, 3 objectives) vs plan-first-then-placement, hv3 ratio: W/T/L = {w}/{t}/{l}",
           f"over {len(p4)} cells; mean diff {p4['diff'].mean():+.4f}. By latency source:", ""]
    for src, g in p4.groupby("latency_source"):
        md.append(f"- {src}: W/T/L {'/'.join(map(str, wtl(g)))}, mean diff {g['diff'].mean():+.4f}")
    md += ["", "Placement changes only latency (accuracy and API cost are placement-independent), so the two searches",
           "differ only in how they spend budget along the latency axis.", ""]

    # ---- S5
    md += ["## S5: PENDING", "", "X2 held-out data (eval_x2 / HotpotQA extra) has not landed on origin/v2-lease1. It will be",
           "opened only after the registration tag (already pushed). Re-run scripts/search/s5_rescore.py when it lands.", ""]

    # ---- scalability
    sc_path = OUT / "scalability_SIMULATED.csv"
    if sc_path.exists():
        sc = pd.read_csv(sc_path)
        ss = summarize(sc, ["n_agents", "method"], ["hv_ratio", "verified"])
        ss.to_csv(OUT / "summary_scalability_SIMULATED.csv", index=False)
        md += ["## Scalability (SIMULATED, not measured)", "",
               "Synthetic 3-tier workflows; gains, label errors and pair interactions sampled from the 11 measured settings",
               "(agentqo/search/scalability.py). 200 verified plans; HV ratio vs a long oracle NSGA-II (pop 200, 300 gens).", "",
               "| agents | " + " | ".join(sorted(sc.method.unique())) + " |", "|---|" + "---|" * sc.method.nunique()]
        for n, g in ss.groupby("n_agents"):
            g = g.set_index("method")
            md.append(f"| {n} | " + " | ".join(f"{g.loc[m, 'hv_ratio_mean']:.3f} [{g.loc[m, 'hv_ratio_ci_low']:.3f}, {g.loc[m, 'hv_ratio_ci_high']:.3f}]"
                                                for m in sorted(sc.method.unique())) + " |")
        md.append("")
        plot_scalability(ss)

    md += ["## Completeness", "", "Settings in this run: " + ", ".join(settings) + ".",
           "Pending (not yet on origin/v2-lease1 as complete plan sets): X2 (S5), X3 cross-family 729 (40/200 problems when",
           "last checked), X5 MATH-500, X6 7B/32B, X7 coding, laptop q4."]
    (OUT / "hypotheses_search.md").write_text("\n".join(md) + "\n")
    plot_hv_vs_budget(s2, settings)
    plot_fronts(d2)
    plot_3d(d3)
    print("\n".join(md))


def plot_hv_vs_budget(s2, settings):
    meth = [MAIN, "nsga2_indep_add", "abacus", "greedy_uv", "rule_confident_uv", "random"]
    fig, axes = plt.subplots(3, 4, figsize=(15, 10), sharey=True)
    for ax, s in zip(axes.flat, settings):
        for c, m in zip(COLORS, meth):
            g = s2[(s2.setting == s) & (s2.method == m)].sort_values("budget_frac")
            ax.plot(g.budget_frac * 100, g.hv_ratio_mean, color=c, lw=2, marker="o", ms=4,
                    ls="--" if m == "abacus" else "-", label=m + (" (= indep_add on these spaces)" if m == "abacus" else ""))
            ax.fill_between(g.budget_frac * 100, g.hv_ratio_ci_low, g.hv_ratio_ci_high, color=c, alpha=0.15, lw=0)
        ax.set_title(f"{s} ({g.n_plans.iloc[0]} plans)", fontsize=9)
        ax.axhline(0.95, color="#888", lw=0.8, ls=":")
        ax.set_xscale("log"); ax.set_xticks([1, 2, 5, 10, 20]); ax.set_xticklabels(["1", "2", "5", "10", "20"])
        ax.grid(alpha=0.2)
    axes.flat[-1].axis("off")
    axes.flat[-1].legend(*axes.flat[0].get_legend_handles_labels(), loc="center")
    fig.supxlabel("verification budget (% of plans)"); fig.supylabel("hypervolume ratio (found / true)")
    fig.tight_layout(); fig.savefig(FIG / "hv_ratio_vs_budget.png", dpi=130); plt.close(fig)


def plot_fronts(d2):
    """True front vs the front found by NSGA-II pairwise m3 and independence (seed 0, 5% and 10%) for 729 / 1,024 plans."""
    fig, axes = plt.subplots(2, 2, figsize=(12, 9))
    for row, s in enumerate(["math_tiers", "complex_q15_7"]):
        st = load_setting(s, with_latency=False)
        terms = label_terms(st)
        for col, frac in enumerate((0.05, 0.10)):
            ax = axes[row, col]
            c = st.cost / st.cost.max()
            ax.scatter(c, st.acc, s=6, color="#c3c2b7", label="all plans")
            tf = true_front(st); o = np.argsort(c[tf])
            ax.step(c[tf][o], st.acc[tf][o], where="post", color="#222", lw=2, label="true front")
            for col_c, m in reversed(list(zip(COLORS, [MAIN, "nsga2_indep_add"]))):  # main drawn on top
                V = METHODS_2D[m](st, budget_for(st.size, frac), np.random.default_rng(0), terms=terms)
                r = np.array(V.rows)
                from agentqo.search.ground_truth import pareto_mask
                f = r[pareto_mask(np.c_[st.cost[r], -st.acc[r]])]; o = np.argsort(c[f])
                ax.scatter(c[r], st.acc[r], s=14, color=col_c, alpha=0.5)
                ax.step(c[f][o], st.acc[f][o], where="post", color=col_c, lw=2, label=f"{m} front (verified)")
            ax.set_title(f"{s}: {st.size} plans, budget {int(frac*100)}% (B={budget_for(st.size, frac)}), seed 0", fontsize=9)
            ax.set_xlabel("API cost / max plan cost"); ax.set_ylabel("accuracy"); ax.grid(alpha=0.2)
    axes[0, 0].legend(fontsize=8, loc="lower right")
    fig.tight_layout(); fig.savefig(FIG / "fronts_729_1024.png", dpi=130); plt.close(fig)


def plot_scalability(ss):
    fig, ax = plt.subplots(figsize=(7, 4.5))
    for c, m in zip(COLORS, sorted(ss.method.unique())):
        g = ss[ss.method == m].sort_values("n_agents")
        ax.plot(g.n_agents, g.hv_ratio_mean, color=c, lw=2, marker="o", ms=5, label=m)
        ax.fill_between(g.n_agents, g.hv_ratio_ci_low, g.hv_ratio_ci_high, color=c, alpha=0.15, lw=0)
    ax.set_xlabel("agents (3 tiers each)"); ax.set_ylabel("HV ratio vs oracle (200 verified plans)")
    ax.set_title("SIMULATED scalability (synthetic workflows from measured distributions)", fontsize=10)
    ax.grid(alpha=0.2); ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(FIG / "scalability_SIMULATED.png", dpi=130); plt.close(fig)


def plot_3d(d3):
    s3 = d3.groupby(["setting", "method", "budget_frac"]).hv3_ratio.mean().reset_index()
    settings = list(dict.fromkeys(s3.setting))
    fig, axes = plt.subplots(3, 4, figsize=(15, 10), sharey=True)
    for ax, s in zip(axes.flat, settings):
        for c, m in zip(COLORS, ["joint_nsga2_pairwise_m3", "plan_first_nsga2_pairwise_m3", "random_3d"]):
            g = s3[(s3.setting == s) & (s3.method == m)].sort_values("budget_frac")
            ax.plot(g.budget_frac * 100, g.hv3_ratio, color=c, lw=2, marker="o", ms=4, label=m)
        src = d3[d3.setting == s].latency_source.iloc[0]
        ax.set_title(f"{s} (latency: {src})", fontsize=8)
        ax.set_xscale("log"); ax.set_xticks([1, 2, 5, 10, 20]); ax.set_xticklabels(["1", "2", "5", "10", "20"])
        ax.grid(alpha=0.2)
    axes.flat[-1].axis("off")
    axes.flat[-1].legend(*axes.flat[0].get_legend_handles_labels(), loc="center")
    fig.supxlabel("verification budget (% of plans)"); fig.supylabel("accuracy-cost-p95 hypervolume ratio")
    fig.tight_layout(); fig.savefig(FIG / "hv3_joint_vs_plan_first.png", dpi=130); plt.close(fig)


if __name__ == "__main__":
    main()
