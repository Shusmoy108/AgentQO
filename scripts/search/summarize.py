def ci(x):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    if len(x) < 2 or np.std(x) == 0:
        return (np.mean(x) if len(x) else np.nan,) * 2
    h = stats.t.ppf(0.975, len(x) - 1) * np.std(x, ddof=1) / np.sqrt(len(x))
    return np.mean(x) - h, np.mean(x) + h


def summarize(d, keys, metrics):
    rows = []
    for k, g in d.groupby(keys):
        r = dict(zip(keys, k))
        for m in metrics:
            lo, hi = ci(g[m])
            r[f"{m}_mean"], r[f"{m}_ci_low"], r[f"{m}_ci_high"] = g[m].mean(), lo, hi
        rows.append(r)
    return pd.DataFrame(rows)


def paired(d, metric, a, b):
    """Per (setting, budget_frac) cell: W / T / L of method a vs b on metric (higher is better)."""
    out = []
    for (s, f), g in d.groupby(["setting", "budget_frac"]):
        x = g[g.method == a].set_index("seed")[metric]
        y = g[g.method == b].set_index("seed")[metric]
        diff = (x - y).dropna()
        lo, hi = ci(diff)
        m = diff.mean()
        res = "W" if m > TAU and lo > 0 else "L" if m < -TAU and hi < 0 else "T"
        out.append({"setting": s, "budget_frac": f, "a": a, "b": b, "diff": m, "ci_low": lo, "ci_high": hi, "res": res})
    return pd.DataFrame(out)


def wtl(p):
    c = p.res.value_counts()
    return int(c.get("W", 0)), int(c.get("T", 0)), int(c.get("L", 0))


